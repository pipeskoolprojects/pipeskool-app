"use client";
// update367: BANK SALARY PAYMENT SHEET — the generator, under Muster Roll & Wages.
// Shows what each sheet will contain BEFORE the file is written, because a bank upload is
// not something you want to discover is wrong after it has gone out.
import { useEffect, useState } from "react";
import { inr } from "@/lib/data";
import { buildPaymentSheets, narrationFor } from "@/lib/bankPayment";
import { exportBankPaymentXlsx } from "@/lib/payrollExport";

const NAVY = "#1f2a4b";

function Card({ icon, title, people, amount, sub, warn }) {
  return (
    <div style={{ border: "1px solid " + (warn ? "#fdba74" : "var(--border)"), background: warn ? "#fff7ed" : "var(--card)",
                  borderRadius: 10, padding: 12, flex: "1 1 190px", minWidth: 170 }}>
      <div style={{ fontSize: 17 }}>{icon}</div>
      <div style={{ fontWeight: 700, fontSize: 13, color: NAVY, margin: "6px 0 2px" }}>{title}</div>
      <div className="muted" style={{ fontSize: 11.5 }}>{people} · <b>{inr(amount)}</b></div>
      {sub && <div className="muted" style={{ fontSize: 10.5, marginTop: 3 }}>{sub}</div>}
    </div>
  );
}

export default function BankPaymentPanel({ month }) {
  const [b, setB] = useState(null);
  const [err, setErr] = useState(""); const [busy, setBusy] = useState(false);

  useEffect(() => {
    setB(null); setErr("");
    buildPaymentSheets(month).then(setB).catch(e => setErr(e.message));
  }, [month]);

  async function gen() {
    setBusy(true); setErr("");
    try { await exportBankPaymentXlsx(b); } catch (e) { setErr(e.message); }
    finally { setBusy(false); }
  }

  if (err) return <div className="panel"><div className="error" style={{ whiteSpace: "pre-wrap" }}>{err}</div></div>;
  if (!b) return <div className="panel"><div className="muted">Building the payment sheets…</div></div>;

  const nothing = !b.staff.length && !b.labour.length && !b.union.length && !b.contractor.length;

  return (
    <div className="panel">
      <b style={{ fontSize: 13 }}>Bank Salary Payment Sheet — {month}</b>
      <div className="muted" style={{ fontSize: 12, marginTop: 2, marginBottom: 12 }}>
        One Excel file, one sheet per payment type. Every amount is the <b>net already generated by payroll</b> — nothing is recalculated here, so the file and the payslips cannot disagree. Narration: <b>{narrationFor(month)}</b>.
      </div>

      {b.debitMissing && (
        <div className="note amber" style={{ marginBottom: 10, fontSize: 12.5 }}>
          <b>The company debit account is not set.</b> The file will generate with that column blank and your bank will reject it. Set <code>company.debit_account_no</code> — it came with update 361.
        </div>
      )}

      <div style={{ display: "flex", gap: 10, flexWrap: "wrap", marginBottom: 12 }}>
        <Card icon="🏦" title="Direct — Staff" people={`${b.staff.length} people`} amount={b.totals.staff} />
        <Card icon="🏦" title="Direct — Labour" people={`${b.labour.length} people`} amount={b.totals.labour} />
        <Card icon="👥" title="Union workers" people={`${b.union.length} people`} amount={b.totals.union} />
        <Card icon="🧱" title="Contractor payments" people={`${b.contractor.length} contractor(s)`} amount={b.totals.contractor}
              sub="net of advances already paid to them" />
        {b.missing.length > 0 && (
          <Card icon="⚠️" warn title="Missing bank details" people={`${b.missing.length} people`} amount={b.totals.missing}
                sub="excluded from every sheet — follow up first" />
        )}
      </div>

      {b.contractor.length > 0 && (
        <div className="muted" style={{ fontSize: 11.5, marginBottom: 10 }}>
          Contractor lines: {b.contractor.map(c => `${c.name} ${inr(c.amount)}${c.netted ? ` (wages ${inr(c.wages)} − advances ${inr(c.netted)})` : ""}`).join(" · ")}
        </div>
      )}

      {b.missing.length > 0 && (
        <div className="note amber" style={{ marginBottom: 12, fontSize: 12 }}>
          <b>{b.missing.length} person(s) will NOT be paid by this file — {inr(b.totals.missing)} held back.</b>
          <div style={{ marginTop: 4 }}>
            {b.missing.slice(0, 8).map(m => `${m.name} (${m.why})`).join(" · ")}
            {b.missing.length > 8 ? ` … and ${b.missing.length - 8} more` : ""}
          </div>
          <div style={{ marginTop: 4 }}>They are listed on their own sheet in the file, marked NOT FOR UPLOAD.</div>
        </div>
      )}

      {/* what the bank will actually receive */}
      {b.labour.length > 0 && (<>
        <div className="muted" style={{ fontSize: 12, fontWeight: 700, marginBottom: 6 }}>Preview — Direct Labour sheet (first 3 rows)</div>
        <div style={{ overflowX: "auto", marginBottom: 14 }}>
          <table>
            <thead><tr>{["Debit A/c", "Amount", "Benef. IFSC", "Benef. A/c", "Narration", "Benef. Name", "Benef. Bank"]
              .map(h => <th key={h} style={{ fontSize: 10.5 }}>{h}</th>)}</tr></thead>
            <tbody>
              {b.labour.slice(0, 3).map((x, i) => (
                <tr key={i}>
                  <td style={{ fontSize: 11.5 }}>{x.debit || "—"}</td>
                  <td style={{ fontSize: 11.5 }}>{inr(x.amount)}</td>
                  <td style={{ fontSize: 11.5 }}>{x.ifsc}</td>
                  <td style={{ fontSize: 11.5 }}>{x.account}</td>
                  <td style={{ fontSize: 11.5 }}>{x.narration}</td>
                  <td style={{ fontSize: 11.5, fontWeight: 600 }}>{x.name}</td>
                  <td style={{ fontSize: 11.5 }}>{x.bankName}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </>)}

      <div style={{ display: "flex", gap: 10, alignItems: "center", flexWrap: "wrap" }}>
        <button className="primary" onClick={gen} disabled={busy || nothing}>
          {busy ? "Generating…" : "⬇ Generate payment sheet (Excel)"}
        </button>
        <b style={{ fontSize: 13, color: NAVY }}>Total to be paid {inr(b.totals.all)}</b>
        {nothing && <span className="muted" style={{ fontSize: 12 }}>Nothing payable for {month} — generate payroll first.</span>}
      </div>

      <div className="muted" style={{ fontSize: 10.5, marginTop: 10 }}>
        Account numbers are written as <b>text</b>, not numbers — a 14-digit account in a numeric cell becomes 5.02012E+13 and the bank rejects the file. Contractors are one sheet, one row each. Both are easy to change if your bank wants otherwise.
      </div>
    </div>
  );
}
