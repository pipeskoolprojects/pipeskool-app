create or replace function fn_today_quote() returns text
language plpgsql security definer set search_path = public as $$
declare q text;
begin
  select text into q from daily_quotes where quote_date = current_date;
  if q is null then
    update daily_quotes set quote_date = current_date
    where id = (select id from daily_quotes where quote_date is null order by random() limit 1)
    returning text into q;
  end if;
  return q;
end $$;
grant execute on function fn_today_quote() to anon, authenticated;

