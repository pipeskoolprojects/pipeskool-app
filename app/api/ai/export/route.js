// update421: /api/ai/export — builds a real .xlsx on the server (exceljs) from an assistant dataset.
// Auth: caller's Supabase JWT. Nothing is read from the database here — the rows come from the previous tool result.
import { createClient } from "@supabase/supabase-js";
import ExcelJS from "exceljs";
export const runtime = "nodejs";

export async function buildXlsx(ds, meta = {}) {
  const wb = new ExcelJS.Workbook(); wb.creator = "Pipeskool Assistant"; wb.created = new Date();
  const ws = wb.addWorksheet(String(ds.title || "Data").replace(/[\\/?*[\]:]/g, " ").slice(0, 31) || "Data");
  const cols = (ds.columns || []).map(c => String(c)); const rows = (ds.rows || []).map(r => (Array.isArray(r) ? r : Object.values(r || {})).map(v => v == null ? "" : (typeof v === "object" ? JSON.stringify(v) : v)));
  ws.addRow(["Pipeskool Projects Pvt. Ltd."]).font = { bold: true, size: 14, color: { argb: "FFFF7A1A" } };
  ws.addRow([ds.title || "Report"]).font = { bold: true, size: 12 };
  ws.addRow([`Generated by ${meta.by || "—"} · ${meta.at || new Date().toISOString().slice(0, 16).replace("T", " ")} IST · ${rows.length} rows${meta.filters ? " · " + meta.filters : ""}`]).font = { italic: true, size: 9, color: { argb: "FF6B7280" } };
  ws.addRow([]);
  const h = ws.addRow(cols); h.eachCell(c => { c.font = { bold: true, color: { argb: "FFFFFFFF" } }; c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFFF7A1A" } }; c.border = { bottom: { style: "thin" } }; });
  rows.forEach(r => ws.addRow(r));
  // totals for numeric columns (amount-like)
  if (rows.length) { const tot = cols.map((c, i) => /amount|value|total|outstanding|paid|hours|ot|qty|pending|received|ordered|balance/i.test(c) && rows.every(r => r[i] === "" || typeof r[i] === "number") ? rows.reduce((s2, r) => s2 + (Number(r[i]) || 0), 0) : (i === 0 ? "TOTAL" : "")); const tr = ws.addRow(tot); tr.font = { bold: true }; tr.eachCell(c => { c.border = { top: { style: "thin" } }; }); }
  cols.forEach((c, i) => { ws.getColumn(i + 1).width = Math.min(60, Math.max(12, ...[c, ...rows.slice(0, 300).map(r => String(r[i] ?? ""))].map(x => x.length + 2))); if (/amount|value|total|rate|outstanding|paid/i.test(c)) ws.getColumn(i + 1).numFmt = "#,##0.00"; });
  ws.views = [{ state: "frozen", ySplit: 5 }];
  return Buffer.from(await wb.xlsx.writeBuffer());
}

export async function POST(req) {
  try {
    const auth = req.headers.get("authorization") || ""; const token = auth.startsWith("Bearer ") ? auth.slice(7) : null;
    if (!token) return new Response("Login required", { status: 401 });
    const sb = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY, { auth: { persistSession: false } });
    const { data } = await sb.auth.getUser(token); if (!data?.user) return new Response("Login required", { status: 401 });
    const { dataset, meta } = await req.json();
    if (!dataset?.columns?.length) return new Response("No data", { status: 400 });
    const buf = await buildXlsx(dataset, meta || {});
    const name = String(dataset.title || "pipeskool-report").replace(/[^A-Za-z0-9 _-]+/g, "").trim().replace(/\s+/g, "_").slice(0, 60) || "pipeskool-report";
    console.log("AI_EXPORT_XLSX", JSON.stringify({ rows: (dataset.rows || []).length, bytes: buf.length }));
    return new Response(buf, { status: 200, headers: { "content-type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", "content-disposition": `attachment; filename="${name}.xlsx"`, "content-length": String(buf.length) } });
  } catch (e) { console.error("AI_EXPORT_FAILED", JSON.stringify({ error: String(e.message || e).slice(0, 200) })); return new Response("Export failed", { status: 500 }); }
}
